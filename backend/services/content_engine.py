async def generate_content(product):
    """
    product 結構範例：
    {
        "name": "中車線素雅絲巾大方包",
        "description": "中車線素雅絲巾大實用，好搭配",
        ...
    }
    """

    prompt = f"""
{PERSONA_PROMPT}

{MASTER_PROMPT}

商品名稱：{product.get('name', '')}
商品描述：{product.get('description', '')}
    """

    raw = await call_openai(prompt)
    if not raw:
        return {}

    result = {}
    for line in raw.split("\n"):
        if ":" in line:
            key, val = line.split(":", 1)
            result[key.strip()] = val.strip()

    # 確保一定有輸出
    result.setdefault("L1", "其他 Others")
    result.setdefault("L2", "其他")
    result.setdefault("L3", "其他")

    return result
